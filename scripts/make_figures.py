"""Draw the comparison charts and save results JSON/CSV into docs/ (all from real result files).

    python -m scripts.make_figures
"""
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from src.reporting import results_loader as R
from src.utils.config_loader import PROJECT_ROOT

OUT = PROJECT_ROOT / "docs" / "figures"
COLORS = {"no_replay": "#d1495b", "general_replay": "#edae49", "full_replay": "#00798c"}


def fig_phase8():
    df = R.phase8_comparison()
    fig, ax = plt.subplots(figsize=(9, 4.5))
    w, x = 0.25, range(len(df))
    for i, (col, lab) in enumerate([("new_facts", "New facts"), ("old_knowledge", "Old knowledge"), ("reasoning", "Reasoning")]):
        bars = ax.bar([p + (i - 1) * w for p in x], df[col] * 100, w, label=lab)
        ax.bar_label(bars, fmt="%.0f", fontsize=8)
    ax.set_xticks(list(x)); ax.set_xticklabels(df["model"], fontsize=8, rotation=10)
    ax.set_ylabel("Accuracy (%)"); ax.set_ylim(0, 112); ax.set_title("Final exam (220 questions): A vs B vs C")
    ax.legend(ncol=3, loc="upper center", bbox_to_anchor=(0.5, -0.18), frameon=False)
    fig.tight_layout(); fig.savefig(OUT / "phase8_comparison.png", dpi=160); plt.close(fig)


def fig_continual():
    df = R.continual_table()
    panels = [("acc_taught_so_far", "Facts taught so far: accuracy (%)"), ("acc_earlier_cycles_facts", "Earlier-cycle facts kept (%)"),
              ("acc_old", "Old knowledge (%)"), ("acc_reasoning", "Reasoning (%)"), ("forgetting_rate", "Forgetting rate (%)")]
    fig, axes = plt.subplots(1, 5, figsize=(20, 3.8))
    for ax, (col, title) in zip(axes, panels):
        for arm in R.ARM_ORDER:
            d = df[df["arm"] == arm].dropna(subset=[col])
            ax.plot(d["cycle"], d[col] * 100, marker="o", color=COLORS[arm], label=R.ARM_LABELS[arm])
        ax.set_title(title, fontsize=10); ax.set_xlabel("cycle"); ax.set_xticks(range(1, 6)); ax.set_ylim(0, 105); ax.grid(alpha=.25)
    axes[0].legend(fontsize=8, frameon=False)
    fig.suptitle("Continual learning over 5 cycles (6 new facts per cycle)", y=1.02)
    fig.tight_layout(); fig.savefig(OUT / "continual_curves.png", dpi=160, bbox_inches="tight"); plt.close(fig)


def fig_heatmaps():
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.6), sharey=True)
    for ax, arm in zip(axes, R.ARM_ORDER):
        m = R.fact_group_matrix(arm)
        im = ax.imshow(m.values * 100, vmin=0, vmax=100, cmap="YlGnBu", aspect="auto")
        ax.set_xticks(range(5)); ax.set_xticklabels([f"G{g}" for g in m.columns]); ax.set_yticks(range(len(m))); ax.set_yticklabels(m.index)
        ax.set_title(R.ARM_LABELS[arm]); ax.set_xlabel("fact group (taught in cycle N)")
        for i in range(m.shape[0]):
            for j in range(m.shape[1]):
                ax.text(j, i, f"{m.values[i, j] * 100:.0f}", ha="center", va="center", fontsize=8, color="black" if m.values[i, j] < .7 else "white")
    axes[0].set_ylabel("exam taken after cycle")
    fig.suptitle("Does the model still know each group of facts?", y=1.03)
    fig.tight_layout(); fig.savefig(OUT / "retention_heatmaps.png", dpi=160, bbox_inches="tight"); plt.close(fig)


def _md(df, pct=(), nd=1):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if v is None or v != v:
                cells.append("-")
            elif c in pct:
                cells.append(f"{v * 100:.{nd}f}%")
            elif isinstance(v, float):
                cells.append(f"{v:.{nd}f}")
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def write_results_md():
    p8 = R.phase8_comparison()
    cont = R.continual_table()
    cols = ["arm_label", "cycle", "n_train_examples", "n_general_replay", "n_previous_replay", "acc_this_cycle_facts",
            "acc_earlier_cycles_facts", "acc_taught_so_far", "acc_old", "acc_reasoning", "forgetting_rate",
            "training_seconds", "gate_would_pass"]
    pct = ("acc_this_cycle_facts", "acc_earlier_cycles_facts", "acc_taught_so_far", "acc_old", "acc_reasoning", "forgetting_rate")
    text = ["# Experimental results", "",
            "Generated by `python -m scripts.make_figures` from the files in `experiments/results/`. Nothing here is typed by hand.", "",
            "## Phase 8: final exam, 220 questions", "",
            _md(p8, pct=("new_facts", "old_knowledge", "reasoning", "forgetting_rate")), "",
            "![phase 8](figures/phase8_comparison.png)", "",
            "## Dev-set settings (Phase 8 tuning, not the final exam)", "",
            _md(R.tuning_table(), pct=("dev_knowledge", "dev_reasoning", "dev_forgetting", "paraphrase_acc"), nd=1), "",
            "## Phase 9: 5 cycles, 6 facts per cycle, one adapter carried forward", "",
            "Columns: `acc_this_cycle_facts` = the 6 facts just taught; `acc_earlier_cycles_facts` = facts from earlier cycles; "
            "`forgetting_rate` = share of the original model's correct old-knowledge/reasoning answers now wrong; "
            "`gate_would_pass` = study-mode verdict (the chain continued regardless).", "",
            _md(cont[cols], pct=pct), "",
            "![curves](figures/continual_curves.png)", "", "![heatmaps](figures/retention_heatmaps.png)", "",
            f"Gate verdicts: {int(cont['gate_would_pass'].sum())} of {len(cont)} cycles would have been promoted.", ""]
    (PROJECT_ROOT / "docs" / "experimental_results.md").write_text("\n".join(text))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    fig_phase8(); fig_continual(); fig_heatmaps(); write_results_md()
    (PROJECT_ROOT / "docs" / "results" / "summary.json").write_text(json.dumps(R.summary(), indent=2, default=float))
    R.continual_table().drop(columns=["acc_by_fact_group", "gate_failed_checks"]).to_csv(PROJECT_ROOT / "docs" / "results" / "continual_by_cycle.csv", index=False)
    R.phase8_comparison().to_csv(PROJECT_ROOT / "docs" / "results" / "phase8_comparison.csv", index=False)
    print("saved to", OUT)


if __name__ == "__main__":
    main()
